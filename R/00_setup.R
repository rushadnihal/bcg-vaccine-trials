packages <- c("metafor", "metadat", "here", "dplyr", "readr", "knitr")

missing <- packages[!packages %in% rownames(installed.packages())]
if (length(missing) > 0) {
  # A CRAN mirror must be set explicitly when running via Rscript
  install.packages(missing, repos = "https://cloud.r-project.org")
}

suppressPackageStartupMessages(
  invisible(lapply(packages, library, character.only = TRUE))
)

# --- Paths -------------------------------------------------------------------
dir_data    <- here::here("data", "processed")
dir_figures <- here::here("outputs", "figures")
dir_tables  <- here::here("outputs", "tables")
dir_reports <- here::here("reports")

for (d in c(dir_data, dir_figures, dir_tables, dir_reports)) {
  dir.create(d, recursive = TRUE, showWarnings = FALSE)
}

# --- Settings ----------------------------------------------------------------
set.seed(2026)
options(digits = 4)

# --- Report helpers ----------------------------------------------------------
# Each script writes a Markdown report to reports/ (renders nicely on GitHub).
#   rpt <- report_start("01_data_prep", "Data preparation")
#   report_text(rpt, "Some sentence.")
#   report_table(rpt, my_df, caption = "Table 1")
#   report_figure(rpt, "forest_plot.png", caption = "Forest plot")

report_start <- function(name, title) {
  path <- file.path(dir_reports, paste0(name, ".md"))
  writeLines(c(
    paste("#", title), "",
    paste0("_Generated by `R/", name, ".R` on ",
           format(Sys.time(), "%Y-%m-%d %H:%M"),
           " (R ", getRversion(), ", metafor ", packageVersion("metafor"), ")_"),
    ""
  ), path)
  path
}

report_text <- function(path, ...) {
  cat(paste0(...), "\n\n", file = path, append = TRUE, sep = "")
}

report_heading <- function(path, text, level = 2) {
  report_text(path, strrep("#", level), " ", text)
}

report_table <- function(path, df, caption = NULL, digits = 3) {
  if (!is.null(caption)) report_text(path, "**", caption, "**")
  tbl <- knitr::kable(as.data.frame(df), format = "pipe", digits = digits)
  cat(tbl, sep = "\n", file = path, append = TRUE)
  cat("\n", file = path, append = TRUE)
}

report_figure <- function(path, figure_file, caption = "") {
  # Relative link from reports/ to outputs/figures/
  report_text(path, "![", caption, "](../outputs/figures/", figure_file, ")")
  if (nzchar(caption)) report_text(path, "_", caption, "_")
}

message("Setup complete. metafor version: ", packageVersion("metafor"))
